const assert = require('node:assert/strict');
const { createActionRouter, actionBindings } = require('../src/gameplay/action-router.ts');
const router = createActionRouter();
let throws = 0, pauses = 0, ready = true;
router.bind({ sling: { run: () => throws++, available: () => ready }, pause: { run: () => pauses++ } });
assert.equal(router.request('sling'), false, 'Cinematic/paused input cannot fire');
assert.equal(router.request('pause'), true, 'Pause can resume a disabled player controller');
router.setHeld('key:W', 'forward');
assert.equal(router.read().forward, 0);
router.setEnabled(true);
router.setHeld('key:W', 'forward'); router.setHeld('pointer:1', 'forward');
assert.equal(router.read().forward, 1, 'Two forward sources do not double movement');
router.setHeld('pointer:1');
assert.equal(router.read().forward, 1, 'Virtual release must preserve physical W');
router.setHeld('pointer:2', 'right');
assert.ok(Math.abs(Math.hypot(router.read().x, router.read().forward) - 1) < 1e-10);
router.setHeld('key:W');
assert.equal(router.read().x, 1);
router.setAnalog('stick', -.5, .5);
assert.ok(Math.abs(router.read().x - .5) < 1e-10);
router.setHeld('pointer:2');
assert.equal(router.read().x, -.5, 'Releasing keys cannot release an independent stick');
router.setHeld('key:L', 'aimRight');
assert.equal(router.read().aimX, 1);
assert.equal(router.request('sling'), true); assert.equal(throws, 1);
ready = false; assert.equal(router.request('sling'), false); assert.equal(throws, 1);
router.setEnabled(false);
assert.equal(router.read().forward, 0); assert.equal(router.read().aimX, 0); assert.equal(router.read().held.size, 0);
router.setEnabled(true); assert.equal(router.read().x, 0, 'Handoff does not restore stale input');
assert.equal(actionBindings.ShiftLeft, 'dodge'); assert.equal(actionBindings.ShiftRight, 'dodge'); assert.equal(actionBindings.Space, 'jump');
assert.equal(pauses, 1);
console.log('PASS: independent held sources, normalised movement, analog/aim ownership, action availability, pause and cinematic cancellation.');
