const { chromium } = require(process.argv[2]);
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const out = path.resolve(process.argv[4] || 'docs/implementation/evidence/m1-2026-11-11');
fs.mkdirSync(out, { recursive: true });
const url = process.argv[3] || 'http://127.0.0.1:4181/saul.html?inspect=1';

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
  const page = await browser.newPage({ viewport: { width: 1366, height: 900 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(url);
  await page.locator('#enter').waitFor({ state: 'visible', timeout: 60000 });
  const state = () => page.locator('canvas').evaluate(el => JSON.parse(el.dataset.cinematic));
  await page.locator('#enter').click();
  await page.waitForTimeout(300);
  console.log('INITIAL', await state());
  await page.screenshot({ path: path.join(out, '01-camp-entry.png') });
  await page.keyboard.press('KeyE');
  assert.equal((await state()).cueCount, 0, 'Cannot speak outside the interaction radius');
  await page.keyboard.down('KeyW'); await page.waitForTimeout(1550); await page.keyboard.up('KeyW');
  await page.locator('#speak').waitFor({ state: 'visible' });
  await page.locator('#speak').click();
  await page.keyboard.press('KeyE');
  assert.equal((await state()).cueCount, 1, 'Duplicate Speak ignored');
  const waitTime = async time => page.waitForFunction(t => JSON.parse(document.querySelector('canvas').dataset.cinematic).time >= t, time, { timeout: 50000 });
  await waitTime(9.6);
  await page.waitForFunction(() => JSON.parse(document.querySelector('canvas').dataset.cinematic).saulMouth.some(w => w > .3), undefined, { timeout: 2500 });
  await page.screenshot({ path: path.join(out, '02-saul-speaking.png') });
  console.log('SAUL', await state());
  await page.locator('#pause').click();
  await page.waitForTimeout(150);
  const frozen = await state();
  await page.waitForTimeout(700);
  const after = await state();
  assert.equal(after.time, frozen.time, 'Cue freezes on Pause');
  assert.equal(after.audio, 'suspended', 'Audio freezes on Pause');
  assert.deepEqual(after.mouth, frozen.mouth, 'Mouth freezes with audio');
  await page.locator('#pause').click();
  await waitTime(16.4);
  await page.waitForFunction(() => JSON.parse(document.querySelector('canvas').dataset.cinematic).davidMouth.some(w => w > .3), undefined, { timeout: 2500 });
  await page.screenshot({ path: path.join(out, '03-david-speaking.png') });
  console.log('DAVID', await state());
  await page.locator('#sound').click();
  await page.waitForFunction(() => JSON.parse(document.querySelector('canvas').dataset.cinematic).muted);
  assert.equal(await page.locator('#caption').isVisible(), true, 'Muted playback keeps captions');
  await page.locator('#sound').click();
  await waitTime(25.0);
  await page.screenshot({ path: path.join(out, '04-soldier-reaction.png') });
  await waitTime(31);
  await page.screenshot({ path: path.join(out, '05-saul-blessing.png') });
  await waitTime(40);
  assert.equal((await state()).completionCount, 1);
  assert.equal((await state()).cue, false);
  await page.screenshot({ path: path.join(out, '06-control-returned.png') });
  const old = (await state()).position;
  await page.keyboard.down('KeyS'); await page.waitForTimeout(500); await page.keyboard.up('KeyS');
  assert.ok((await state()).position.z > old.z + .15, 'Player control returns');
  await page.keyboard.down('KeyW');
  await page.waitForFunction(() => JSON.parse(document.querySelector('canvas').dataset.cinematic).canSpeak, undefined, { timeout: 5000 });
  await page.keyboard.up('KeyW');
  await page.locator('#speak').click();
  await page.waitForTimeout(700);
  await page.locator('#reset').click();
  await page.waitForFunction(() => !JSON.parse(document.querySelector('canvas').dataset.cinematic).cue);
  assert.equal((await state()).cue, false);
  assert.equal((await state()).time, 0);
  await page.waitForTimeout(1000);
  assert.equal((await state()).completionCount, 0, 'Restart cancels old completion');

  for (const [name, width, height] of [['portrait', 390, 844], ['landscape', 844, 390]]) {
    const phone = await browser.newContext({ viewport: { width, height }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
    const tab = await phone.newPage();
    tab.on('pageerror', e => errors.push(e.message));
    await tab.goto(url);
    await tab.locator('#enter').waitFor({ state: 'visible', timeout: 60000 });
    await tab.locator('#enter').click();
    await tab.locator('#entry').waitFor({ state: 'hidden' });
    await tab.locator('#move-pad').waitFor({ state: 'visible' });
    const pad = await tab.locator('#move-pad').boundingBox();
    assert.ok(pad && pad.width > 0, 'Touch stick visible');
    const cdp = await phone.newCDPSession(tab);
    const x = pad.x + pad.width / 2, y = pad.y + pad.height / 2;
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - 32 }] });
    await tab.waitForTimeout(1750);
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await tab.locator('#speak').waitFor({ state: 'visible' });
    await tab.locator('#speak').click();
    await tab.waitForFunction(() => JSON.parse(document.querySelector('canvas').dataset.cinematic).time >= 16.4, undefined, { timeout: 30000 });
    assert.equal(await tab.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No horizontal overflow');
    await tab.screenshot({ path: path.join(out, `07-${name}.png`) });
    for (const id of ['sound', 'pause', 'reset']) assert.ok((await tab.locator(`#${id}`).boundingBox()).height >= 48, 'Essential touch target is at least 48px high');
    await tab.locator('#pause').click();
    await tab.waitForFunction(() => JSON.parse(document.querySelector('canvas').dataset.cinematic).paused);
    const phoneTime = await tab.locator('canvas').evaluate(el => JSON.parse(el.dataset.cinematic).time);
    await tab.waitForTimeout(350);
    assert.equal(await tab.locator('canvas').evaluate(el => JSON.parse(el.dataset.cinematic).time), phoneTime);
    await tab.locator('#pause').click();
    await tab.waitForFunction(() => !JSON.parse(document.querySelector('canvas').dataset.cinematic).paused);
    await phone.close();
  }
  assert.deepEqual(errors, [], 'No browser runtime errors');
  const result = { checked: new Date().toISOString(), browser: await browser.version(), assertions: 'PASS', layouts: ['1366x900', '390x844 touch emulation', '844x390 touch emulation'], errors };
  fs.writeFileSync(path.join(out, 'browser-check.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
